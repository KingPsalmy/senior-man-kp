// Run after replacing a source photo: node scripts/optimize-media.mjs
// Content hashes let browsers cache these files without keeping an old picture.
import sharp from "sharp"
import { createHash } from "node:crypto"
import { mkdir, readFile, writeFile } from "node:fs/promises"

await mkdir("public/media", { recursive: true })
const assets = {}
for (const name of ["hero-pic", "hero-pic-left", "hero-pic-left-2", "hero-pic-left-3", "logo-white"]) {
  const source = await readFile(`public/${name}.png`)
  const output = await sharp(source).resize({ width: name === "logo-white" ? 320 : 1536, withoutEnlargement: true }).webp({ quality: 85, effort: 6 }).toBuffer()
  const hash = createHash("sha256").update(output).digest("hex").slice(0, 12)
  const path = `/media/${name}.${hash}.webp`
  await writeFile(`public${path}`, output)
  assets[name] = path
  console.log(`${name}: ${source.length.toLocaleString()} → ${output.length.toLocaleString()} bytes`)
}
await writeFile("src/lib/media-assets.ts", `// Generated by scripts/optimize-media.mjs; original PNGs are preserved.\nexport const mediaAssets = ${JSON.stringify(assets, null, 2)} as const\n`)
